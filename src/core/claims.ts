// ============================================================
// 「完成式宣称」话术检测（纯函数，零依赖）
// 用途：AI 在聊天里说「已帮你写入档案/已经填好/已完成」但实际没有
// 产出任何创作时，界面据此弹警示戳穿。
// 保守策略：宁可漏报不可误报——只在「已/已经」紧跟完成式动词、且邻近
// 片段不含否定（没/未/尚未）或疑问（吗/呢/?/？）时才判定为宣称。
// 实现：按小句（，。；！？!?;\n 等）切分，逐句找「已…动词」片段；
// 中英混排与多余空白均可容忍。
// ============================================================

/** 完成式动词表：已/已经 紧跟这些词才算宣称（保守：表外的词一律放行） */
const DONE_VERBS = "写入|写进|记录|保存|填好|填写|创建|生成|完成|建好|加进|加入|补上|更新";

/** 小句切分：中英标点与换行都算边界 */
const CLAUSE_SPLIT = /[，。；！？!?;,\n]+/;

/** 邻近否定/疑问守卫：小句里出现这些字样就不算完成式宣称（"还没有完成"/"已经写入了吗？"等） */
const NEG_GUARD = /[没未吗呢?？]/;

/** 「已(经) + 可选修饰(帮你/帮我/把…等空白与代词) + 动词」的宽松衔接（空白容忍）；
 *  (?!度|率) 排除"完成度/更新率"这类名词化表述，避免"已完成度还很低"误报 */
const CLAIM = new RegExp(`已(?:经)?[\\s]*(?:帮你[\\s]*|帮我[\\s]*|把[\\s]*)?(?:${DONE_VERBS})(?!度|率)`);

/**
 * 检测文本是否含「完成式宣称」话术。
 * 保守匹配：命中形如「已/已经」紧跟「写入/写进/记录/保存/填好/填写/创建/
 * 生成/完成/建好/加进/加入/补上/更新」的小句片段才返回 true；
 * 所在小句含「没/未/尚未/吗/呢/?/？」等否定或疑问标记时一律放行（返回 false），
 * 避免误伤"还没有完成""已经写入了吗？"这类正常表述。
 */
export function claimsCompletion(text: string): boolean {
  if (!text) return false;
  for (const clause of text.split(CLAUSE_SPLIT)) {
    if (!clause.trim()) continue;
    if (NEG_GUARD.test(clause)) continue;
    if (CLAIM.test(clause)) return true;
  }
  return false;
}
